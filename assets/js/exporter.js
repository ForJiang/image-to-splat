// 导出：.ply（二进制彩色点云）与 .splat（antimatter15 32 字节/泼溅格式）。
// Blob 生成与保存分离，便于测试与复用。

async function saveAs(blob, filename) {
  // 桌面端（Electron 壳注入 window.i2sDesktop）走系统保存对话框，否则浏览器下载
  const dk = typeof window !== 'undefined' && window.i2sDesktop;
  if (dk?.saveBlob) {
    try { await dk.saveBlob(blob, filename); } catch (err) { console.error(err); }
    return;
  }
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = filename;
  document.body.appendChild(a);
  a.click();
  a.remove();
  setTimeout(() => URL.revokeObjectURL(url), 4000);
}

// 兼容 Blender / CloudCompare / SuperSplat 的彩色点云
export function toPLYBlob({ positions, colors, count }) {
  const header = [
    'ply',
    'format binary_little_endian 1.0',
    'comment Generated by Image2Splat — single-view gaussian splat cloud',
    `element vertex ${count}`,
    'property float x',
    'property float y',
    'property float z',
    'property uchar red',
    'property uchar green',
    'property uchar blue',
    'end_header',
  ].join('\n') + '\n';

  const hb = new TextEncoder().encode(header);
  const body = new Uint8Array(count * 15);
  const dv = new DataView(body.buffer);
  for (let i = 0; i < count; i++) {
    const o = i * 15;
    dv.setFloat32(o, positions[i * 3], true);
    dv.setFloat32(o + 4, positions[i * 3 + 1], true);
    dv.setFloat32(o + 8, positions[i * 3 + 2], true);
    body[o + 12] = Math.min(255, Math.round(colors[i * 3] * 255));
    body[o + 13] = Math.min(255, Math.round(colors[i * 3 + 1] * 255));
    body[o + 14] = Math.min(255, Math.round(colors[i * 3 + 2] * 255));
  }
  return new Blob([hb, body], { type: 'application/octet-stream' });
}

export function exportPLY(cloud, filename) {
  saveAs(toPLYBlob(cloud), filename || `image2splat-${cloud.count}pts.ply`);
}

// antimatter15 .splat：pos f32×3 + scale f32×3 + rgba u8×4 + rot u8×4
// 按体积降序排列；单位四元数 (255,128,128,128) 在常见解码约定下均为恒等旋转。
export function toSplatBlob({ positions, colors, sizes, count }) {
  const order = Array.from({ length: count }, (_, i) => i);
  order.sort((a, b) => sizes[b] - sizes[a]);

  const buf = new ArrayBuffer(count * 32);
  const dv = new DataView(buf);
  for (let k = 0; k < count; k++) {
    const i = order[k];
    const o = k * 32;
    dv.setFloat32(o, positions[i * 3], true);
    dv.setFloat32(o + 4, positions[i * 3 + 1], true);
    dv.setFloat32(o + 8, positions[i * 3 + 2], true);
    const s = Math.max(sizes[i] * 0.45, 1e-5);
    dv.setFloat32(o + 12, s, true);
    dv.setFloat32(o + 16, s, true);
    dv.setFloat32(o + 20, s, true);
    dv.setUint8(o + 24, Math.min(255, Math.round(colors[i * 3] * 255)));
    dv.setUint8(o + 25, Math.min(255, Math.round(colors[i * 3 + 1] * 255)));
    dv.setUint8(o + 26, Math.min(255, Math.round(colors[i * 3 + 2] * 255)));
    dv.setUint8(o + 27, 255);
    dv.setUint8(o + 28, 255);
    dv.setUint8(o + 29, 128);
    dv.setUint8(o + 30, 128);
    dv.setUint8(o + 31, 128);
  }
  return new Blob([buf], { type: 'application/octet-stream' });
}

export function exportSplat(cloud, filename) {
  saveAs(toSplatBlob(cloud), filename || `image2splat-${cloud.count}.splat`);
}

export function exportCanvasPNG(canvas, filename) {
  canvas.toBlob((b) => {
    if (b) saveAs(b, filename);
  }, 'image/png');
}
